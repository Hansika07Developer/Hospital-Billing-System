CREATE DATABASE IF NOT EXISTS hospital_billing;
USE hospital_billing;
CREATE TABLE IF NOT EXISTS users(
 id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(100) UNIQUE NOT NULL,
 password VARCHAR(255) NOT NULL, role VARCHAR(50) DEFAULT 'Admin');
CREATE TABLE IF NOT EXISTS patients(
 id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(150) NOT NULL,age INT,gender VARCHAR(20),
 phone VARCHAR(30),address VARCHAR(255),created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS bills(
 id INT AUTO_INCREMENT PRIMARY KEY,patient_id INT NOT NULL,bill_date DATE NOT NULL,
 doctor VARCHAR(150),
 total_amount DECIMAL(12,2) DEFAULT 0,paid_amount DECIMAL(12,2) DEFAULT 0,
 payment_status VARCHAR(30) DEFAULT 'Pending',notes TEXT,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(patient_id) REFERENCES patients(id));
CREATE TABLE IF NOT EXISTS bill_items(
 id INT AUTO_INCREMENT PRIMARY KEY,bill_id INT NOT NULL,item_type VARCHAR(50) NOT NULL,
 description VARCHAR(255) NOT NULL,quantity DECIMAL(10,2) DEFAULT 1,
 unit_price DECIMAL(12,2) DEFAULT 0,amount DECIMAL(12,2) DEFAULT 0,
 FOREIGN KEY(bill_id) REFERENCES bills(id) ON DELETE CASCADE);
